/**
 * One-time generator for scripts/db/data/catalog/image-manifest.mjs
 * Run: node scripts/db/lib/generate-image-manifest.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { SEED_AUCTION_CATALOG } from '../data/auctions.mjs';
import { resolveAssetImageUrls, clearCommonsSearchCache } from './wikimedia-images.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.resolve(__dirname, '../data/catalog/image-manifest.mjs');

function flattenAssets() {
  return SEED_AUCTION_CATALOG.flatMap((auction) =>
    auction.lotGroups.flatMap((group) => group.assets),
  );
}

async function main() {
  clearCommonsSearchCache();
  const manifest = {};
  const assets = flattenAssets();

  for (const asset of assets) {
    console.log(`Resolving images for: ${asset.title}`);
    try {
      const urls = await resolveAssetImageUrls(asset, console);
      manifest[asset.assetId] = urls;
      console.log(`  -> ${urls.length} url(s)`);
    } catch (error) {
      console.error(`  !! failed: ${error.message}`);
      manifest[asset.assetId] = [];
    }
    await new Promise((resolve) => setTimeout(resolve, 2_500));
  }

  const body = `/** Auto-generated by scripts/db/lib/generate-image-manifest.mjs */\nexport const SEED_IMAGE_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
  fs.writeFileSync(OUTPUT, body, 'utf8');
  console.log(`Wrote ${OUTPUT}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
